-- review-service schema. Same columns/constraints/index names as the monolith's hotel_review, so legacy reviews
-- keep their ids. Differences: hotel_id / user_id / booking_id have no foreign keys (other services own them), and
-- the public card's reviewer name, stay date and room type are stored with the review (the monolith joined
-- app_user, booking and room at read time).

CREATE TABLE hotel_review (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id      bigint        NOT NULL,
    user_id       bigint        NOT NULL,
    booking_id    bigint        NOT NULL,
    rating        smallint      NOT NULL,
    comment       varchar(1000) NOT NULL,
    created_at    timestamp(6)  NOT NULL,
    reviewer_name varchar(255),
    stayed_on     date,
    room_type     varchar(255),
    CONSTRAINT uk_hotel_review_booking UNIQUE (booking_id),
    CONSTRAINT chk_hotel_review_rating CHECK (rating BETWEEN 1 AND 5)
);
-- review list by newest, and summary / sort by rating, for one hotel
CREATE INDEX idx_hotel_review_hotel_created ON hotel_review (hotel_id, created_at);
CREATE INDEX idx_hotel_review_hotel_rating ON hotel_review (hotel_id, rating);
