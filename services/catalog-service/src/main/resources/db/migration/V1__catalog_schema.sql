-- catalog-service schema. Column types, constraints and index names match the monolith's tables (created by
-- Hibernate ddl-auto) so legacy rows can be copied with their ids. Differences:
--   * hotel.owner_id has no foreign key: users live in auth-service.
--   * inventory_hold (new): rooms taken out of inventory per booking (booking-service), see InventoryHoldService.
--   * hotel_rating (new): rating read model pushed by review-service, used by the search rating filter.

CREATE TABLE location (
    id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city  varchar(100) NOT NULL,
    state varchar(100) NOT NULL,
    CONSTRAINT uk_location_city_state UNIQUE (city, state)
);
CREATE INDEX idx_location_state ON location (state);

CREATE TABLE city_photo (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id  bigint       NOT NULL REFERENCES location (id),
    file_name    varchar(255) NOT NULL,
    content_type varchar(50)  NOT NULL,
    size_bytes   bigint       NOT NULL,
    data         bytea        NOT NULL,
    source_page  varchar(500),
    image_page   varchar(500),
    artist       varchar(200),
    license      varchar(100),
    created_at   timestamp(6),
    CONSTRAINT uk_city_photo_location UNIQUE (location_id)
);

CREATE TABLE hotel (
    hotel_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           varchar(255) NOT NULL,
    city           varchar(255),
    location_id    bigint       NOT NULL REFERENCES location (id),
    owner_id       bigint       NOT NULL,
    amenities      text[],
    created_at     timestamp(6),
    updated_at     timestamp(6),
    contact_person varchar(255),
    address        varchar(255),
    phone_number   varchar(255),
    email          varchar(255),
    location       varchar(255),
    active         boolean      NOT NULL,
    deleted_at     timestamp(6)
);
CREATE INDEX idx_hotel_owner ON hotel (owner_id);
CREATE INDEX idx_hotel_location ON hotel (location_id);

CREATE TABLE hotel_photo (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id     bigint       NOT NULL REFERENCES hotel (hotel_id),
    file_name    varchar(255) NOT NULL,
    content_type varchar(50)  NOT NULL,
    size_bytes   bigint       NOT NULL,
    data         bytea        NOT NULL,
    created_at   timestamp(6)
);
CREATE INDEX idx_hotel_photo_hotel ON hotel_photo (hotel_id);

CREATE TABLE room (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id    bigint        NOT NULL REFERENCES hotel (hotel_id),
    type        varchar(255)  NOT NULL,
    base_price  numeric(10, 2) NOT NULL,
    amenities   text[],
    total_count integer       NOT NULL,
    capacity    integer       NOT NULL,
    created_at  timestamp(6),
    updated_at  timestamp(6),
    deleted_at  timestamp(6)
);
CREATE INDEX idx_room_hotel ON room (hotel_id);

CREATE TABLE room_photo (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id      bigint       NOT NULL REFERENCES room (id),
    file_name    varchar(255) NOT NULL,
    content_type varchar(50)  NOT NULL,
    size_bytes   bigint       NOT NULL,
    data         bytea        NOT NULL,
    created_at   timestamp(6)
);
CREATE INDEX idx_room_photo_room ON room_photo (room_id);

CREATE TABLE inventory (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id     bigint        NOT NULL REFERENCES hotel (hotel_id),
    room_id      bigint        NOT NULL REFERENCES room (id),
    date         date          NOT NULL,
    booked_count integer       NOT NULL DEFAULT 0,
    total_count  integer       NOT NULL,
    surge_factor numeric(5, 2) NOT NULL,
    price        numeric(10, 2) NOT NULL,
    city         varchar(255)  NOT NULL,
    closed       boolean       NOT NULL,
    created_at   timestamp(6),
    updated_at   timestamp(6),
    CONSTRAINT unique_hotel_room_date UNIQUE (hotel_id, room_id, date),
    -- Database-level guard against overbooking and negative inventory.
    CONSTRAINT chk_inventory_booked_count CHECK (booked_count >= 0 AND booked_count <= total_count)
);

CREATE TABLE inventory_hold (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hold_key       uuid           NOT NULL,
    booking_id     bigint,
    hotel_id       bigint         NOT NULL REFERENCES hotel (hotel_id),
    room_id        bigint         NOT NULL REFERENCES room (id),
    check_in_date  date           NOT NULL,
    check_out_date date           NOT NULL,
    rooms_count    integer        NOT NULL,
    amount         numeric(12, 2) NOT NULL,
    status         varchar(20)    NOT NULL,
    created_at     timestamp(6),
    updated_at     timestamp(6),
    CONSTRAINT uk_inventory_hold_key UNIQUE (hold_key),
    CONSTRAINT uk_inventory_hold_booking UNIQUE (booking_id),
    CONSTRAINT chk_inventory_hold_status CHECK (status IN ('HELD', 'RELEASED')),
    CONSTRAINT chk_inventory_hold_dates CHECK (check_out_date > check_in_date),
    CONSTRAINT chk_inventory_hold_rooms CHECK (rooms_count > 0)
);
-- Upcoming-booking checks before deleting a hotel / room type.
CREATE INDEX idx_inventory_hold_hotel ON inventory_hold (hotel_id, status, check_out_date);
CREATE INDEX idx_inventory_hold_room ON inventory_hold (room_id, status, check_out_date);
-- Reconciliation of holds no booking has claimed.
CREATE INDEX idx_inventory_hold_unattached ON inventory_hold (created_at) WHERE booking_id IS NULL AND status = 'HELD';

CREATE TABLE hotel_rating (
    hotel_id     bigint       PRIMARY KEY,
    rating_sum   bigint       NOT NULL,
    rating_count bigint       NOT NULL,
    updated_at   timestamp(6) NOT NULL,
    CONSTRAINT chk_hotel_rating_values CHECK (rating_sum >= 0 AND rating_count >= 0)
);
