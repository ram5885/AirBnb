-- booking-service schema. Column types and constraints match the monolith's guest / payment / booking tables so
-- legacy rows can be copied with their ids. Differences:
--   * no foreign keys to hotel / room / app_user: those live in catalog-service and auth-service;
--   * booking.hotel_owner_id scopes the manager views (the monolith joined hotel.owner_id);
--   * booking.hold_key / hold_status track the rooms held in catalog-service's inventory;
--   * booking.hotel_name ... user_email are a snapshot used when the other services are unavailable.

CREATE TABLE guest (
    id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint,
    name    varchar(255) NOT NULL,
    gender  varchar(255),
    age     integer,
    CONSTRAINT guest_gender_check CHECK (gender IN ('MALE', 'FEMALE', 'OTHER'))
);
CREATE INDEX idx_guest_user ON guest (user_id);

CREATE TABLE payment (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id      varchar(255)   NOT NULL,
    razorpay_order_id   varchar(255),
    razorpay_payment_id varchar(255),
    razorpay_refund_id  varchar(255),
    currency            varchar(3),
    failure_reason      varchar(255),
    payment_status      varchar(255)   NOT NULL,
    amount              numeric(10, 2) NOT NULL,
    method              varchar(20),
    created_at          timestamp(6),
    updated_at          timestamp(6),
    CONSTRAINT payment_transaction_id_key UNIQUE (transaction_id),
    CONSTRAINT payment_razorpay_order_id_key UNIQUE (razorpay_order_id),
    CONSTRAINT payment_razorpay_payment_id_key UNIQUE (razorpay_payment_id),
    CONSTRAINT payment_method_check CHECK (method IN ('ONLINE', 'PAY_AT_HOTEL')),
    CONSTRAINT payment_payment_status_check CHECK (payment_status IN
        ('PENDING', 'CONFIRMED', 'CANCELLED', 'FAILED', 'REFUND_PENDING', 'REFUNDED'))
);
CREATE INDEX idx_payment_refund ON payment (razorpay_refund_id);

CREATE TABLE payment_webhook_event (
    event_id    varchar(100) PRIMARY KEY,
    event_type  varchar(100) NOT NULL,
    received_at timestamp(6)
);

CREATE TABLE booking (
    booking_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id       bigint         NOT NULL,
    room_id        bigint         NOT NULL,
    user_id        bigint         NOT NULL,
    hotel_owner_id bigint         NOT NULL,
    rooms_count    integer        NOT NULL,
    amount         numeric(12, 2),
    check_in_date  date           NOT NULL,
    check_out_date date           NOT NULL,
    created_at     timestamp(6),
    updated_at     timestamp(6),
    payment_id     bigint REFERENCES payment (id),
    booking_status varchar(255)   NOT NULL,
    hold_key       uuid           NOT NULL,
    hold_status    varchar(20)    NOT NULL,
    hotel_name     varchar(255),
    hotel_city     varchar(255),
    hotel_state    varchar(255),
    room_type      varchar(255),
    room_capacity  integer,
    user_name      varchar(255),
    user_email     varchar(255),
    CONSTRAINT booking_payment_id_key UNIQUE (payment_id),
    CONSTRAINT uk_booking_hold_key UNIQUE (hold_key),
    CONSTRAINT booking_booking_status_check CHECK (booking_status IN
        ('RESERVED', 'ACCEPTED', 'CONFIRMED', 'CANCELLED', 'EXPIRED')),
    CONSTRAINT booking_hold_status_check CHECK (hold_status IN ('HELD', 'RELEASE_PENDING', 'RELEASED'))
);
CREATE INDEX idx_booking_hotel ON booking (hotel_id);
CREATE INDEX idx_booking_room ON booking (room_id);
CREATE INDEX idx_booking_user ON booking (user_id);
CREATE INDEX idx_booking_owner ON booking (hotel_owner_id, created_at);
CREATE INDEX idx_booking_release_pending ON booking (updated_at) WHERE hold_status = 'RELEASE_PENDING';

CREATE TABLE booking_guest (
    booking_id bigint NOT NULL REFERENCES booking (booking_id),
    guest_id   bigint NOT NULL REFERENCES guest (id),
    PRIMARY KEY (booking_id, guest_id)
);
