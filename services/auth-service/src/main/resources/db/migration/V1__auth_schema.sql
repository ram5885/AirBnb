-- auth-service schema: accounts and roles. Same columns/constraints as the monolith's app_user/user_roles,
-- so legacy rows (with their ids and BCrypt hashes) can be copied as-is.

CREATE TABLE app_user (
    id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email    varchar(255) NOT NULL,
    name     varchar(255),
    password varchar(255) NOT NULL,
    CONSTRAINT app_user_email_key UNIQUE (email)
);

CREATE TABLE user_roles (
    user_id bigint NOT NULL REFERENCES app_user (id),
    roles   varchar(255),
    CONSTRAINT user_roles_roles_check CHECK (roles IN ('GUEST', 'HOTEL_MANAGER'))
);

CREATE INDEX idx_user_roles_user ON user_roles (user_id);
